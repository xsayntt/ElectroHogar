-- Rutas y permisos de menú para las pantallas disponibles en la aplicación.
-- Puede ejecutarse más de una vez: conserva los IDs existentes y actualiza permisos.
-- Requiere que TIPO_USUARIO contenga el rol "Administrador".

USE electrohogar;

SET @tipo_admin = (
    SELECT ID_TIPO FROM TIPO_USUARIO WHERE NOMBRE_TIPO = 'Administrador' LIMIT 1
);
SET @siguiente_menu = (SELECT IFNULL(MAX(ID_MENU), 0) FROM MENU_RUTA);

SET @id_menu = (SELECT ID_MENU FROM MENU_RUTA WHERE RUTA = 'FrmUsuarios' LIMIT 1);
INSERT INTO MENU_RUTA (ID_MENU, MEN_ID_MENU, NOMBRE_OPCION, RUTA, ORDEN)
SELECT (@siguiente_menu := @siguiente_menu + 1), NULL, 'Gestión de usuarios', 'FrmUsuarios', 1
 WHERE @id_menu IS NULL;
SET @id_usuarios = (SELECT ID_MENU FROM MENU_RUTA WHERE RUTA = 'FrmUsuarios' LIMIT 1);

SET @id_menu = (SELECT ID_MENU FROM MENU_RUTA WHERE RUTA = 'FrmFacturasDetalle' LIMIT 1);
INSERT INTO MENU_RUTA (ID_MENU, MEN_ID_MENU, NOMBRE_OPCION, RUTA, ORDEN)
SELECT (@siguiente_menu := @siguiente_menu + 1), NULL, 'Ventas y Facturación', 'FrmFacturasDetalle', 2
 WHERE @id_menu IS NULL;
SET @id_venta = (SELECT ID_MENU FROM MENU_RUTA WHERE RUTA = 'FrmFacturasDetalle' LIMIT 1);

SET @id_menu = (SELECT ID_MENU FROM MENU_RUTA WHERE RUTA = 'FrmFacturas' LIMIT 1);
INSERT INTO MENU_RUTA (ID_MENU, MEN_ID_MENU, NOMBRE_OPCION, RUTA, ORDEN)
SELECT (@siguiente_menu := @siguiente_menu + 1), NULL, 'Control y Anulación de Facturas', 'FrmFacturas', 3
 WHERE @id_menu IS NULL;
SET @id_facturas = (SELECT ID_MENU FROM MENU_RUTA WHERE RUTA = 'FrmFacturas' LIMIT 1);

SET @id_menu = (SELECT ID_MENU FROM MENU_RUTA WHERE RUTA = 'FrmCreditos' LIMIT 1);
INSERT INTO MENU_RUTA (ID_MENU, MEN_ID_MENU, NOMBRE_OPCION, RUTA, ORDEN)
SELECT (@siguiente_menu := @siguiente_menu + 1), NULL, 'Gestión de Créditos y Pagos', 'FrmCreditos', 4
 WHERE @id_menu IS NULL;
SET @id_creditos = (SELECT ID_MENU FROM MENU_RUTA WHERE RUTA = 'FrmCreditos' LIMIT 1);

-- Ruta interna requerida por los procedimientos de venta; no se muestra en el menú.
SET @id_menu = (SELECT ID_MENU FROM MENU_RUTA WHERE RUTA = 'FrmVenta' LIMIT 1);
INSERT INTO MENU_RUTA (ID_MENU, MEN_ID_MENU, NOMBRE_OPCION, RUTA, ORDEN)
SELECT (@siguiente_menu := @siguiente_menu + 1), NULL, 'Permiso interno de ventas', 'FrmVenta', 5
 WHERE @id_menu IS NULL;
SET @id_venta_interno = (SELECT ID_MENU FROM MENU_RUTA WHERE RUTA = 'FrmVenta' LIMIT 1);

SET @id_menu = (SELECT ID_MENU FROM MENU_RUTA WHERE RUTA = 'FrmReportesVentas' LIMIT 1);
INSERT INTO MENU_RUTA (ID_MENU, MEN_ID_MENU, NOMBRE_OPCION, RUTA, ORDEN)
SELECT (@siguiente_menu := @siguiente_menu + 1), NULL, 'Reportes de Ventas', 'FrmReportesVentas', 6
 WHERE @id_menu IS NULL;
SET @id_reportes = (SELECT ID_MENU FROM MENU_RUTA WHERE RUTA = 'FrmReportesVentas' LIMIT 1);

INSERT INTO PRIVILEGIO
    (ID_MENU, ID_TIPO, PUEDE_CREAR, PUEDE_ELIMINAR, PUEDE_ACTUALIZAR, PUEDE_LEER)
SELECT @id_usuarios, @tipo_admin, 1, 1, 1, 1
 WHERE @tipo_admin IS NOT NULL AND @id_usuarios IS NOT NULL
ON DUPLICATE KEY UPDATE
    PUEDE_CREAR = VALUES(PUEDE_CREAR), PUEDE_ELIMINAR = VALUES(PUEDE_ELIMINAR),
    PUEDE_ACTUALIZAR = VALUES(PUEDE_ACTUALIZAR), PUEDE_LEER = VALUES(PUEDE_LEER);

